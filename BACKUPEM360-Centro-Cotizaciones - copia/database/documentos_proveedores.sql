-- Biblioteca de documentos disponibles para proveedores autenticados.

create table if not exists public."DocumentosProveedores" (
    id bigint generated by default as identity primary key,
    proyecto_id bigint not null references public."Proyectos"(id) on delete cascade,
    servicio text,
    titulo text not null,
    comentario text,
    ruta_archivo text not null,
    created_at timestamptz not null default now()
);

alter table public."DocumentosProveedores"
add column if not exists servicio text;

alter table public."DocumentosProveedores"
add column if not exists comentario text;

create index if not exists idx_documentos_proveedores_proyecto_fecha
on public."DocumentosProveedores" (proyecto_id, created_at desc);

alter table public."DocumentosProveedores" enable row level security;
revoke all on table public."DocumentosProveedores" from anon;
grant select, insert, update, delete on table public."DocumentosProveedores" to authenticated;

drop policy if exists "authenticated consulta documentos proveedores" on public."DocumentosProveedores";
create policy "authenticated consulta documentos proveedores"
on public."DocumentosProveedores" for select to authenticated using (true);

drop policy if exists "administrador administra documentos proveedores" on public."DocumentosProveedores";
create policy "administrador administra documentos proveedores"
on public."DocumentosProveedores" for all to authenticated
using ((select public.es_administrador()))
with check ((select public.es_administrador()));

insert into storage.buckets (id, name, public)
values ('documentos-proveedores', 'documentos-proveedores', true)
on conflict (id) do update set public = true;

revoke all on storage.objects from anon;
grant select, insert, delete on storage.objects to authenticated;

drop policy if exists "authenticated consulta documentos proveedores archivos" on storage.objects;
create policy "authenticated consulta documentos proveedores archivos"
on storage.objects for select to authenticated
using (bucket_id = 'documentos-proveedores');

drop policy if exists "administrador sube documentos proveedores" on storage.objects;
create policy "administrador sube documentos proveedores"
on storage.objects for insert to authenticated
with check (bucket_id = 'documentos-proveedores' and (select public.es_administrador()));

drop policy if exists "administrador borra documentos proveedores" on storage.objects;
create policy "administrador borra documentos proveedores"
on storage.objects for delete to authenticated
using (bucket_id = 'documentos-proveedores' and (select public.es_administrador()));

notify pgrst, 'reload schema';
