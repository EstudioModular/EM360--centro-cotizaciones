create table if not exists public."CotizacionesProveedores" (
    id bigint generated by default as identity primary key,
    proyecto_id bigint not null references public."Proyectos"(id) on delete cascade,
    proveedor text not null,
    servicio text not null check (servicio in ('ebanisteria', 'marmoleros', 'sheetrockeros', 'plomeros', 'electricistas', 'piseros', 'pintores', 'tope')),
    comentario text,
    ruta_archivo text,
    created_at timestamptz not null default now()
);

create index if not exists idx_cotizaciones_proveedor_proyecto_fecha
    on public."CotizacionesProveedores" (proyecto_id, servicio, created_at desc);

alter table public."CotizacionesProveedores" enable row level security;

grant usage on schema public to anon;
grant select, insert on table public."CotizacionesProveedores" to anon;

drop policy if exists "anon puede ver cotizaciones de proveedores" on public."CotizacionesProveedores";
create policy "anon puede ver cotizaciones de proveedores"
on public."CotizacionesProveedores"
for select
to anon
using (true);

drop policy if exists "anon puede crear cotizaciones de proveedores" on public."CotizacionesProveedores";
create policy "anon puede crear cotizaciones de proveedores"
on public."CotizacionesProveedores"
for insert
to anon
with check (true);

insert into storage.buckets (id, name, public)
values ('cotizaciones-proveedores', 'cotizaciones-proveedores', true)
on conflict (id) do update set public = true;

drop policy if exists "anon puede subir imagenes de cotizaciones" on storage.objects;
create policy "anon puede subir imagenes de cotizaciones"
on storage.objects
for insert
to anon
with check (bucket_id = 'cotizaciones-proveedores');

notify pgrst, 'reload schema';
