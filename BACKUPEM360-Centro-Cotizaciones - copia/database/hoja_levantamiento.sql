-- Ejecutar después de portal_proveedores.sql y rls_roles.sql.

alter table public."Perfiles"
add column if not exists especialidad_proveedor text;

create or replace function public.configurar_proveedor(
    correo_proveedor text,
    especialidad text
)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
    if not (select public.es_administrador()) then
        raise exception 'Solo un administrador puede configurar proveedores';
    end if;
    if especialidad not in ('ebanisteria', 'marmoleros', 'sheetrockeros', 'plomeros', 'electricistas', 'piseros', 'pintores') then
        raise exception 'Especialidad no válida';
    end if;
    update public."Perfiles"
    set es_proveedor_portal = true,
        especialidad_proveedor = especialidad
    where id = (select id from auth.users where lower(email) = lower(trim(correo_proveedor)) limit 1);
    if not found then raise exception 'No existe una cuenta invitada con ese correo'; end if;
end;
$$;

revoke all on function public.configurar_proveedor(text, text) from public;
grant execute on function public.configurar_proveedor(text, text) to authenticated;

create table if not exists public."HojasLevantamiento" (
    id bigint generated by default as identity primary key,
    proyecto_id bigint not null references public."Proyectos"(id) on delete cascade,
    servicios_destino text[] not null,
    contenido jsonb not null,
    creado_por text,
    created_at timestamptz not null default now()
);

create index if not exists idx_hojas_levantamiento_proyecto
on public."HojasLevantamiento" (proyecto_id, created_at desc);

alter table public."HojasLevantamiento" enable row level security;
revoke all on table public."HojasLevantamiento" from anon;
grant select, insert, update, delete on table public."HojasLevantamiento" to authenticated;

drop policy if exists "usuarios consultan hojas levantamiento" on public."HojasLevantamiento";
create policy "usuarios consultan hojas levantamiento"
on public."HojasLevantamiento" for select to authenticated using (true);

drop policy if exists "oficiales administran hojas levantamiento" on public."HojasLevantamiento";
create policy "oficiales administran hojas levantamiento"
on public."HojasLevantamiento" for all to authenticated
using ((select public.es_oficial_o_administrador()))
with check ((select public.es_oficial_o_administrador()));

notify pgrst, 'reload schema';
