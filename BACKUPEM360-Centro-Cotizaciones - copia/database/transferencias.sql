create table if not exists public."Transferencias" (
    id bigint generated by default as identity primary key,
    proyecto_id bigint not null references public."Proyectos"(id) on delete cascade,
    comentario text,
    ruta_archivo text,
    created_at timestamptz not null default now(),
    constraint transferencias_con_contenido check (
        comentario is not null or ruta_archivo is not null
    )
);

create index if not exists idx_transferencias_proyecto_fecha
    on public."Transferencias" (proyecto_id, created_at desc);

alter table public."Transferencias" enable row level security;

grant usage on schema public to anon;
grant select, insert on table public."Transferencias" to anon;

drop policy if exists "anon puede ver transferencias" on public."Transferencias";
create policy "anon puede ver transferencias"
on public."Transferencias"
for select
to anon
using (true);

drop policy if exists "anon puede crear transferencias" on public."Transferencias";
create policy "anon puede crear transferencias"
on public."Transferencias"
for insert
to anon
with check (true);

insert into storage.buckets (id, name, public)
values ('transferencias', 'transferencias', true)
on conflict (id) do update set public = true;

drop policy if exists "anon puede subir fotos de transferencias" on storage.objects;
create policy "anon puede subir fotos de transferencias"
on storage.objects
for insert
to anon
with check (bucket_id = 'transferencias');
